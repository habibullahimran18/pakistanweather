/**
 * Generates src/lib/weather/pakistan-map.ts — a simplified SVG path of
 * Pakistan plus lat/lng -> viewBox projection helpers for city markers.
 *
 * Source: johan/world.geo.json PAK.geo.json (Natural Earth derived).
 * Run: bun scripts/generate-map.mjs
 */

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dir, "..");
const OUT = path.join(ROOT, "src", "lib", "weather", "pakistan-map.ts");

const SOURCE_URLS = [
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson",
  "https://raw.githubusercontent.com/johan/world.geo.json/master/countries/PAK.geo.json",
];

let geo = null;
for (const url of SOURCE_URLS) {
  try {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const json = await res.json();
    // Multi-country files: filter to Pakistan
    const features = (json.features ?? []).filter(
      (f) => f.properties?.ADMIN === "Pakistan" || f.properties?.ADMIN === "PAK" || f.properties?.name === "Pakistan" || f.properties?.NAME === "Pakistan" || f.id === "PAK" || f.properties?.ISO_A3 === "PAK"
    );
    if (features.length === 0) throw new Error("Pakistan not found in source");
    geo = { features };
    console.log("Downloaded:", url, `(${features.length} feature(s))`);
    break;
  } catch (e) {
    console.warn("Failed:", url, e.message);
  }
}
if (!geo) throw new Error("Could not download Pakistan GeoJSON");

// ---------- collect polygons ----------
const rings = [];
for (const feature of geo.features ?? [geo]) {
  const geom = feature.geometry;
  if (geom.type === "Polygon") rings.push(...geom.coordinates);
  else if (geom.type === "MultiPolygon") rings.push(...geom.coordinates.map((p) => p[0]));
}
console.log("Rings:", rings.length, "points:", rings.reduce((s, r) => s + r.length, 0));

// ---------- Douglas-Peucker simplification ----------
const perpDist = (p, a, b) => {
  const [x, y] = p, [x1, y1] = a, [x2, y2] = b;
  const dx = x2 - x1, dy = y2 - y1;
  if (dx === 0 && dy === 0) return Math.hypot(x - x1, y - y1);
  const t = ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy);
  const cx = x1 + t * dx, cy = y1 + t * dy;
  return Math.hypot(x - cx, y - cy);
};

function simplify(points, tol) {
  if (points.length <= 3) return points;
  let maxDist = 0, index = 0;
  const a = points[0], b = points[points.length - 1];
  for (let i = 1; i < points.length - 1; i++) {
    const d = perpDist(points[i], a, b);
    if (d > maxDist) { maxDist = d; index = i; }
  }
  if (maxDist > tol) {
    const left = simplify(points.slice(0, index + 1), tol);
    const right = simplify(points.slice(index), tol);
    return [...left.slice(0, -1), ...right];
  }
  return [a, b];
}

// ---------- projection ----------
// Simple equirectangular projection with cos(mid-latitude) correction.
let lngMin = Infinity, lngMax = -Infinity, latMin = Infinity, latMax = -Infinity;
for (const ring of rings) {
  for (const [lng, lat] of ring) {
    lngMin = Math.min(lngMin, lng); lngMax = Math.max(lngMax, lng);
    latMin = Math.min(latMin, lat); latMax = Math.max(latMax, lat);
  }
}
const MID_LAT = (latMin + latMax) / 2;
const COS = Math.cos((MID_LAT * Math.PI) / 180);
const WIDTH = 1000;
const spanX = (lngMax - lngMin) * COS;
const spanY = latMax - latMin;
const HEIGHT = Math.round((spanY / spanX) * WIDTH);

const project = ([lng, lat]) => {
  const x = ((lng - lngMin) / (lngMax - lngMin)) * WIDTH * COS;
  const y = ((latMax - lat) / (latMax - latMin)) * HEIGHT;
  return [x, y];
};

const tol = 0.08; // degrees — tuned for smooth coastline
const simplified = rings.map((r) => simplify(r, tol));
const totalPts = simplified.reduce((s, r) => s + r.length, 0);
console.log("Simplified points:", totalPts, "viewBox:", `${WIDTH}x${HEIGHT}`);

const paths = simplified
  .map((ring) => {
    const pts = ring.map(project);
    return (
      `M${pts.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join("L")}Z`
    );
  })
  .join(" ");

// ---------- city projection helpers ----------
const CITIES = {
  Lahore: { latitude: 31.5204, longitude: 74.3587 },
  Karachi: { latitude: 24.8607, longitude: 67.0011 },
  Islamabad: { latitude: 33.6844, longitude: 73.0479 },
  Peshawar: { latitude: 34.0151, longitude: 71.5249 },
  Quetta: { latitude: 30.1798, longitude: 66.975 },
};

const cityPositions = Object.fromEntries(
  Object.entries(CITIES).map(([name, { latitude, longitude }]) => {
    const [x, y] = project([longitude, latitude]);
    return [name, { x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 }];
  })
);

const file = `/**
 * AUTO-GENERATED by scripts/generate-map.mjs — do not edit manually.
 * Simplified Pakistan outline (Natural Earth via world.geo.json) with an
 * equirectangular projection (cos(mid-lat) corrected) for city markers.
 */

export const PAKISTAN_VIEWBOX = { width: ${WIDTH}, height: ${HEIGHT} } as const;

/** Main landmass + minor islands as SVG path segments. */
export const PAKISTAN_PATH =
  ${JSON.stringify(paths)};

/** Projected city marker positions inside PAKISTAN_VIEWBOX. */
export const PAKISTAN_CITIES: Record<string, { x: number; y: number }> = ${JSON.stringify(cityPositions, null, 2)};

/** Project an arbitrary lat/lng pair into the map viewBox. */
export function projectToMap(latitude: number, longitude: number): { x: number; y: number } {
  const x = ((longitude - ${lngMin.toFixed(6)}) / ${((lngMax - lngMin).toFixed(6))}) * ${WIDTH} * ${COS.toFixed(6)};
  const y = ((${latMax.toFixed(6)} - latitude) / ${((latMax - latMin).toFixed(6))}) * ${HEIGHT};
  return { x, y };
}
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, file);
console.log("Wrote", path.relative(ROOT, OUT));
console.log("City positions:", JSON.stringify(cityPositions, null, 2));
